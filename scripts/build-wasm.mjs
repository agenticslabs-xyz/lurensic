// Builds the Rust core for wasm32 and puts it into @agenticslabs/kagami twice.
// wasm/kagami_core.wasm is imported by the Cloudflare Workers entry, and
// src/engine-bytes.ts embeds the same bytes as base64 for Node, Bun and Deno.
import { execFileSync } from 'node:child_process';
import { copyFileSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
execFileSync('cargo', ['build', '--release', '--target', 'wasm32-unknown-unknown', '-p', 'kagami-core'], {
  cwd: root,
  stdio: 'inherit',
});
const src = join(root, 'target', 'wasm32-unknown-unknown', 'release', 'kagami_core.wasm');
const pkg = join(root, 'packages', 'node');
mkdirSync(join(pkg, 'wasm'), { recursive: true });
copyFileSync(src, join(pkg, 'wasm', 'kagami_core.wasm'));
writeFileSync(
  join(pkg, 'src', 'engine-bytes.ts'),
  '// Generated by scripts/build-wasm.mjs. Do not edit.\n' + `export const ENGINE_BASE64 = '${readFileSync(src).toString('base64')}';\n`,
);
console.log(`Copied kagami_core.wasm (${(statSync(src).size / 1024).toFixed(0)} KiB) to packages/node/wasm/ and embedded it in src/engine-bytes.ts`);
